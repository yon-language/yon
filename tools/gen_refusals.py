#!/usr/bin/env python3
"""Generate runtime/yon_refusals.h from prelude/sys/Refusal.yon.

The place Refusal is the source: its arms, in order (an arm's tag is its
position), and the sentence `sentence` gives each. The header carries the
enumeration of the reasons, the prototype of the runtime's refusal, and the
table of sentences (for yon_sys.c only), so no sentence of refusal is written
by hand in the C.

Usage:
  python tools/gen_refusals.py            # rewrite the header
  python tools/gen_refusals.py --check    # exit 1 if the header is stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "prelude" / "sys" / "Refusal.yon"
OUT = ROOT / "runtime" / "yon_refusals.h"


def strip_comments(text: str) -> str:
    return re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)


def arms_and_sentences():
    text = strip_comments(SRC.read_text())
    m = re.search(r"this\s*>(.*?)\bfun\s+sentence\b", text, re.DOTALL)
    if not m:
        raise SystemExit("gen_refusals: no `this >` clause before `fun sentence`")
    arms = [a.strip() for a in m.group(1).split(":U")]
    if any(not re.fullmatch(r"[A-Z][A-Za-z0-9]*", a) for a in arms):
        raise SystemExit(f"gen_refusals: an arm is not a bare name: {arms}")
    sentences = dict(re.findall(r'^\s*([A-Z][A-Za-z0-9]*)\s*=>\s*"((?:[^"\\]|\\.)*)"',
                                text, re.MULTILINE))
    missing = [a for a in arms if a not in sentences]
    extra = [s for s in sentences if s not in arms]
    if missing or extra:
        raise SystemExit(f"gen_refusals: arms without a sentence {missing}, "
                         f"sentences without an arm {extra}")
    return arms, sentences


def render() -> str:
    arms, sentences = arms_and_sentences()
    lines = [
        "/* yon_refusals.h — GENERATED by tools/gen_refusals.py from",
        " * prelude/sys/Refusal.yon. Do not edit: change the place and regenerate.",
        " *",
        " * The reasons the runtime stops a program, by the tag of their arm, and",
        " * the refusal itself: it writes \"error: \" and the sentence, the words of",
        " * the occasion in their places, and ends the program with exit code 3. */",
        "#ifndef YON_REFUSALS_H",
        "#define YON_REFUSALS_H",
        "#include <stdint.h>",
        "",
        "enum yon_refusal {",
    ]
    for i, a in enumerate(arms):
        lines.append(f"    YON_REFUSAL_{a} = {i},")
    lines += [
        f"    YON_REFUSAL_COUNT = {len(arms)}",
        "};",
        "",
        "/* the words of the occasion: an integer, the bits of a real, a type root,",
        " * the address of a name, or an errno, as the sentence reads them */",
        "_Noreturn void yon_rt_refuse_with(enum yon_refusal r, int64_t a, int64_t b, int64_t c);",
        "int64_t yon_refusal_real(double x);",
        "int64_t yon_refusal_name(const char *s);",
        "const char *yon_refusal_text(int64_t w);",
        "",
        "#endif",
        "",
        "/* the sentences, for the one file that writes them */",
        "#if defined(YON_REFUSAL_SENTENCES) && !defined(YON_REFUSAL_SENTENCES_WRITTEN)",
        "#define YON_REFUSAL_SENTENCES_WRITTEN",
        "static const char *const yon_refusal_sentence[YON_REFUSAL_COUNT] = {",
    ]
    for a in arms:
        lines.append(f'    "{sentences[a]}",')
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print("gen_refusals: runtime/yon_refusals.h is stale; "
                  "run python tools/gen_refusals.py", file=sys.stderr)
            return 1
        print(f"refusals in sync ({len(arms_and_sentences()[0])} reasons)")
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
