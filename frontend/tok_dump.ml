let () =
  let src = In_channel.with_open_text Sys.argv.(1) In_channel.input_all in
  let lexbuf = Lexing.from_string src in
  let buf = Buffer.create 4096 in
  let rec loop () =
    match Lexer.token lexbuf with
    | Parser.EOF -> Buffer.add_string buf "EOF"
    | t -> Buffer.add_string buf (tok_name t); Buffer.add_char buf (Char.chr 32); loop ()
  in
  (try loop () with _ -> exit 2);
  print_string (Buffer.contents buf)
