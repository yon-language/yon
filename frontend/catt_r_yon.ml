(* ─── Family 3 (constructive): higher-dimensional associativity ──────
 *
 * The 1-dimensional associator is just the K_3 polytope (a
 * triangle). The next dimension is the K_4 pentagonator (5 vertices,
 * 5 edges), and in general dim n corresponds to the Stasheff polytope
 * K_{n+2}. Vertices correspond to parenthesizations of n+2 cells (the
 * Catalan number C_{n+1}).
 *
 * For Yon we encode the Stasheff polytope vertices as full
 * parenthesizations and the n-cell coherence as a TmCoh over the
 * pasting scheme that lists all n+2 composable 1-cells. *)

(* A binary tree representing a parenthesization of n+1 cells.
 * Leaf i is the i-th cell; Branch (l, r) means (l ; r). *)
type paren_tree =
  | Leaf of int
  | Branch of paren_tree * paren_tree

(* Generate all parenthesizations of n cells (Catalan numbers).
 *   - 1 cell : 1 way    [Leaf 0]
 *   - 2 cells: 1 way    [Branch (Leaf 0, Leaf 1)]
 *   - 3 cells: 2 ways   [(0;1);2  and  0;(1;2)]
 *   - n cells: C_{n-1}  via the recurrence sum over split point.
 *
 * Returns the list of all trees with leaves 0..n-1 in order. *)
let rec parenthesizations (n : int) (offset : int) : paren_tree list =
  if n = 1 then [Leaf offset]
  else
    let rec build_for_split k acc =
      if k >= n then acc
      else
        let lefts = parenthesizations k offset in
        let rights = parenthesizations (n - k) (offset + k) in
        let combos = List.concat_map
          (fun l -> List.map (fun r -> Branch (l, r)) rights)
          lefts in
        build_for_split (k + 1) (acc @ combos)
    in
    build_for_split 1 []

(* Pasting scheme for n+1 composable 1-cells:
 *   [x_0 : star, x_1 : star, ..., x_n : star,
 *    f_0 : x_0 -> x_1, f_1 : x_1 -> x_2, ..., f_{n-1} : x_{n-1} -> x_n]
 * Used as ps_ctx for the Stasheff coherence at dim n-1. *)
let ps_stasheff (n_cells : int) : ps_ctx =
  let objs = List.init (n_cells + 1)
    (fun i -> (Printf.sprintf "x%d" i, CellStar)) in
  let arrs = List.init n_cells
    (fun i ->
       let src = TmVar (Printf.sprintf "x%d" i) in
       let tgt = TmVar (Printf.sprintf "x%d" (i + 1)) in
       (Printf.sprintf "f%d" i, CellArr (src, tgt, CellStar))) in
  objs @ arrs

(* Build a TmCoh that "is" the composition of cells f_0, ..., f_{n-1}
 * according to a specific parenthesization tree. The result is a 1-cell
 * x_0 -> x_n. *)
let rec tree_to_composition_term (t : paren_tree) : term =
  match t with
  | Leaf i -> TmVar (Printf.sprintf "f%d" i)
  | Branch (l, r) ->
      let l_term = tree_to_composition_term l in
      let r_term = tree_to_composition_term r in
      (* The endpoints of (l ; r) are leftmost(l) and rightmost(r). *)
      let rec leftmost = function
        | Leaf i -> i | Branch (l', _) -> leftmost l' in
      let rec rightmost = function
        | Leaf i -> i + 1 | Branch (_, r') -> rightmost r' in
      let _mid = rightmost l in  (* shared boundary *)
      let lo = leftmost l in
      let hi = rightmost r in
      let src = TmVar (Printf.sprintf "x%d" lo) in
      let tgt = TmVar (Printf.sprintf "x%d" hi) in
      let result_cell = CellArr (src, tgt, CellStar) in
      TmCoh (ps_comp_2, result_cell,
             [("x", src);
              ("y", TmVar (Printf.sprintf "x%d" _mid));
              ("f", l_term);
              ("z", tgt);
              ("g", r_term)])

(* The Stasheff coherence at dimension n connects ANY two
 * parenthesizations of the same sequence of cells. We produce a
 * specific witness 2-cell between the "left-comb"
 *   ((...((f_0 ; f_1) ; f_2) ; ...) ; f_{n-1})
 * and the "right-comb"
 *   (f_0 ; (f_1 ; (f_2 ; (... ; f_{n-1}))))
 *
 * These are two extreme vertices of the Stasheff polytope; for
 * n_cells = 2 there is just one tree, for n_cells = 3 it's the
 * associator (Test 128), for n_cells = 4 it's the pentagonator. *)

let rec left_comb (start : int) (count : int) : paren_tree =
  if count = 1 then Leaf start
  else Branch (left_comb start (count - 1), Leaf (start + count - 1))

let rec right_comb (start : int) (count : int) : paren_tree =
  if count = 1 then Leaf start
  else Branch (Leaf start, right_comb (start + 1) (count - 1))

let stasheff_coherence (n_cells : int) : term =
  let ps = ps_stasheff n_cells in
  let left = tree_to_composition_term (left_comb 0 n_cells) in
  let right = tree_to_composition_term (right_comb 0 n_cells) in
  let base_cell = CellArr (TmVar "x0",
                           TmVar (Printf.sprintf "x%d" n_cells),
                           CellStar) in
  let witness_cell = CellArr (left, right, base_cell) in
  (* Identity substitution: each pasting-scheme var maps to itself. *)
  let sub = List.map (fun (name, _) -> (name, TmVar name)) ps in
  TmCoh (ps, witness_cell, sub)

(* Test entries. *)
let test_stasheff_pentagonator () =
  (* 4 cells: the pentagonator. There are C_3 = 5 parenthesizations. *)
  let trees = parenthesizations 4 0 in
  let coh = stasheff_coherence 4 in
  match coh with
  | TmCoh (ps, CellArr (_, _, base), _) ->
      List.length ps = 9  (* 5 objects + 4 arrows *)
      && List.length trees = 5  (* C_3 = 5 *)
      && (match base with CellArr (s, t, CellStar) ->
            alpha_equiv_term s (TmVar "x0") []
            && alpha_equiv_term t (TmVar "x4") []
            | _ -> false)
  | _ -> false

let test_stasheff_general n =
  (* The coherence at dim n-1 connects extremal parenthesizations.
   * For any n >= 2 the result is a well-formed 2-cell. *)
  let coh = stasheff_coherence n in
  match coh with
  | TmCoh (_, CellArr (_, _, CellArr (s, t, CellStar)), _) ->
      alpha_equiv_term s (TmVar "x0") []
      && alpha_equiv_term t (TmVar (Printf.sprintf "x%d" n)) []
  | _ -> false

(* ─── Family 8 (constructive): strict omega-functoriality ────
 *
 * For every builtin F (binary op, coercion, move-application), strict
 * omega-functoriality demands:
 *
 *   F(id_x) = id_{F(x)}
 *   F(g compose f) = F(g) compose F(f)
 *
 * up to syntactic equality (not just equivalence). *)

let apply_builtin (name : string) (t : term) : term =
  TmCoh ([(name, CellStar)], CellStar, [(name, t)])

let apply_builtin_to_cell (name : string) (f_src : term) (f_tgt : term) : term =
  let fx = apply_builtin name f_src in
  let fy = apply_builtin name f_tgt in
  let result_cell = CellArr (fx, fy, CellStar) in
  TmCoh ([(name, CellStar)], result_cell,
         [(name, TmVar "F_of_f")])

(* Check F(id_x) = id_{F(x)}. *)
let check_preserves_identity (name : string) : bool =
  let x = TmVar "x" in
  let f_id_x = apply_builtin_to_cell name x x in
  let fx = apply_builtin name x in
  match f_id_x with
  | TmCoh (_, CellArr (l, r, _), _) ->
      alpha_equiv_term l fx [] && alpha_equiv_term r fx []
  | _ -> false

(* Check F(g compose f) = F(g) compose F(f). *)
let check_preserves_composition (name : string) : bool =
  let x = TmVar "x" and y = TmVar "y" and z = TmVar "z" in
  let f_cell = CellArr (x, y, CellStar) in
  let g_cell = CellArr (y, z, CellStar) in
  let comp_first =
    match cell_compose f_cell g_cell with
    | Some (_, CellArr (s, t, _)) -> apply_builtin_to_cell name s t
    | _ -> TmVar "ERROR"
  in
  let fx = apply_builtin name x in
  let fz = apply_builtin name z in
  let apply_first_cell = CellArr (fx, fz, CellStar) in
  let apply_first = TmCoh ([(name, CellStar)], apply_first_cell, []) in
  match comp_first, apply_first with
  | TmCoh (_, CellArr (l1, r1, _), _), TmCoh (_, CellArr (l2, r2, _), _) ->
      alpha_equiv_term l1 l2 [] && alpha_equiv_term r1 r2 []
  | _ -> false

let test_functoriality_add () =
  check_preserves_identity "__add" && check_preserves_composition "__add"

let test_functoriality_to_prop () =
  check_preserves_identity "to_prop" && check_preserves_composition "to_prop"

let test_functoriality_apply_move () =
  check_preserves_identity "apply_move"
  && check_preserves_composition "apply_move"
