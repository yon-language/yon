(* catt_r_yon.ml — CATT with R_Yon equality rules, per Rice 2025.
 *
 * Implements the CATT_R_Yon fragment of the type checker federation.
 *
 * CATT (Finster-Mimram 2017) is a dependent type theory whose models
 * are globular weak ∞-categories. Its types are organized by:
 *
 *   - Contexts (telescopes) of variables typed by globular types
 *   - Pasting schemes (ps-contexts) describing pasting diagrams
 *   - Substitutions between contexts
 *   - The judgment Gamma |- t : A
 *
 * Rice 2025 extends CATT with a set R of equality rules. For Yon,
 * R = R_Yon comprises seven families. The crucial property:
 *
 *   Theorem (Rice 2025): For appropriate R, the reduction system
 *   generated by R is strongly normalizing and confluent. Therefore
 *   typechecking of CATT_R is decidable.
 *
 * This module implements the seven families of R_Yon and the
 * decidable equality on CATT_R_Yon types.
 *)

open Surface_ast

(* ─── Globular types ───────────────────────────────────────────────── *)

(* A globular type is a finite tower of cells:
 *
 *   *           — the unique 0-cell (object)
 *   x ->_A y     — a 1-cell from x to y, where A is the type of x, y
 *   alpha ->_{x->y} beta — a 2-cell between 1-cells x -> y
 *   ...
 *
 * We represent this inductively. The base case is Star (objects).
 * The inductive case is Arr (s, t, A) where s and t are terms whose
 * type is A.
 *)

type cell =
  | CellStar                                     (* 0-cell sort *)
  | CellArr of term * term * cell                (* s -> t in cell A *)

and term =
  | TmVar of string                              (* a context variable *)
  | TmCoh of ps_ctx * cell * subst               (* coh_Gamma : A [σ]: a coherence *)
  | TmId of term * cell                          (* identity 1-cell on a term *)

and ps_ctx = (string * cell) list                (* a pasting context *)

and subst = (string * term) list                 (* substitution by name *)

(* ─── Family 1: alpha-renaming (alpha-equivalence) ─────────────────────── *)

(* Two terms are alpha-equivalent if they agree up to renaming of bound
 * variables. In our globular setting, only TmCoh binds variables (via
 * its ps_ctx), so alpha-equivalence amounts to comparing the structure
 * with consistent renaming.
 *
 * For surface Yon, alpha-equivalence is mostly relevant inside lambdas
 * (in function declarations) — those live in the Surface_ast as
 * fun_decl bodies. The CATT layer handles the type-level alpha via the
 * coh constructor.
 *)

let rec alpha_equiv_term (t1 : term) (t2 : term) (renaming : (string * string) list) : bool =
  match t1, t2 with
  | TmVar x, TmVar y ->
      (match List.assoc_opt x renaming with
       | Some y' -> y = y'
       | None -> x = y)
  | TmCoh (ps1, ty1, sub1), TmCoh (ps2, ty2, sub2) ->
      List.length ps1 = List.length ps2
      && List.length sub1 = List.length sub2
      && (let pair_names = List.combine
            (List.map fst ps1) (List.map fst ps2) in
          let ren' = pair_names @ renaming in
          List.for_all2
            (fun (_, c1) (_, c2) -> alpha_equiv_cell c1 c2 ren')
            ps1 ps2
          && alpha_equiv_cell ty1 ty2 ren'
          && List.for_all2
               (fun (k1, t1) (k2, t2) ->
                  (* Substitution keys live in the ps_ctx, so they
                   * must correspond under the same renaming used for
                   * the pasting variables. *)
                  let k1_renamed = List.assoc_opt k1 pair_names in
                  (match k1_renamed with
                   | Some k1' -> k1' = k2
                   | None -> k1 = k2)
                  && alpha_equiv_term t1 t2 ren')
               sub1 sub2)
  | TmId (t1', c1), TmId (t2', c2) ->
      alpha_equiv_term t1' t2' renaming
      && alpha_equiv_cell c1 c2 renaming
  | _, _ -> false

and alpha_equiv_cell (c1 : cell) (c2 : cell) (renaming : (string * string) list) : bool =
  match c1, c2 with
  | CellStar, CellStar -> true
  | CellArr (s1, t1, a1), CellArr (s2, t2, a2) ->
      alpha_equiv_term s1 s2 renaming
      && alpha_equiv_term t1 t2 renaming
      && alpha_equiv_cell a1 a2 renaming
  | _, _ -> false

let family1_alpha_equiv t1 t2 = alpha_equiv_term t1 t2 []

(* ─── Name-invariant canonicalization (weak de Bruijn) ──────────────────────

   The names debt (identified for xleech2 content-addressing): two cells that are
   alpha-equivalent but written with different binder names (x vs y) must map to
   the SAME structure, otherwise hash-consing them gives different addresses and
   content-addressing is defeated.

   canonicalize_term rewrites every BOUND name (introduced by a TmCoh's ps_ctx)
   to a positional canonical name "#<n>" assigned in ps_ctx order. Free TmVars
   (0-cells / real places, bound by no TmCoh) are left intact — they ARE the
   geometric identity and must not be erased. After canonicalization, two
   alpha-equivalent cells are STRUCTURALLY identical, so equality is a direct
   structural compare (O(1) once hash-consed), with no renaming list to carry.

   `env` maps an original bound name to its canonical "#n". `depth` is the next
   free index. Substitution keys live in the binding ps_ctx, so they are
   canonicalized through the same env. *)
let rec canonicalize_term (env : (string * string) list) (t : term) : term =
  match t with
  | TmVar x ->
      (match List.assoc_opt x env with
       | Some canon -> TmVar canon   (* bound: positional name *)
       | None -> TmVar x)            (* free: a real 0-cell, kept as-is *)
  | TmCoh (ps, ty, sub) ->
      (* assign positional canonical names to the ps_ctx binders, in order *)
      let _, rev_env', rev_ps =
        List.fold_left
          (fun (i, e, acc) (name, c) ->
             let canon = "#" ^ string_of_int i in
             let e' = (name, canon) :: e in
             (* the cell of this binder may refer to earlier binders -> use e' *)
             (i + 1, e', (canon, canonicalize_cell e' c) :: acc))
          (0, env, []) ps
      in
      let env' = rev_env' in
      let ps' = List.rev rev_ps in
      let ty' = canonicalize_cell env' ty in
      let sub' =
        List.map
          (fun (k, tm) ->
             let k' = (match List.assoc_opt k env' with Some c -> c | None -> k) in
             (k', canonicalize_term env' tm))
          sub
      in
      TmCoh (ps', ty', sub')
  | TmId (t', c) ->
      TmId (canonicalize_term env t', canonicalize_cell env c)

and canonicalize_cell (env : (string * string) list) (c : cell) : cell =
  match c with
  | CellStar -> CellStar
  | CellArr (s, t, a) ->
      CellArr (canonicalize_term env s, canonicalize_term env t,
               canonicalize_cell env a)

(* The canonical (name-invariant) form of a cell-term: ready for structural
   equality and, ultimately, for content-addressed hash-consing on xleech2. *)
let canonical_form (t : term) : term = canonicalize_term [] t

(* Name-invariant equality: two terms are equal iff their canonical forms are
   structurally identical. Equivalent to alpha-equivalence, but via a single
   normal form rather than a renaming search — the prerequisite for O(1)
   hash-consed equality. *)
let canonical_equal (t1 : term) (t2 : term) : bool =
  canonical_form t1 = canonical_form t2

(* ─── A1: native hash-consing of cells over the canonical form ──────────────

   Once cells have a name-invariant canonical form (above), we can SHARE
   structurally-identical cells: interning a cell returns a single shared node
   for each distinct canonical form. Two geometrically-identical cells then
   become the SAME physical value, so equality is pointer identity (==) instead
   of a structural walk — the O(1) definitional equality the design calls for,
   realized in the compiler (OCaml), where cells actually live, with no FFI and
   no abuse of the runtime arena.

   This mirrors what an xleech2 content-addressed store would do at the C level
   (yon_xheap_put_or_get), but in-process: the canonical form is the content
   key. When a network/serialization layer later needs cells as wire payloads,
   the same canonical form maps directly onto an xleech2 block (the deferred A2).

   The table is keyed by canonical form and maps to the interned representative.
   reset_cell_interning clears it (e.g. between compilation units). *)
let cell_intern_table : (term, term) Hashtbl.t = Hashtbl.create 256

let reset_cell_interning () = Hashtbl.reset cell_intern_table

(* Intern a cell-term: return the unique shared node for its canonical form.
   Structurally-identical cells get the SAME physical representative. *)
let intern_cell (t : term) : term =
  let key = canonical_form t in
  match Hashtbl.find_opt cell_intern_table key with
  | Some shared -> shared
  | None -> Hashtbl.replace cell_intern_table key key; key

(* O(1) equality on interned cells: physical identity. Falls back to canonical
   equality if either side was not interned (defensive). *)
let interned_equal (t1 : term) (t2 : term) : bool =
  let a = intern_cell t1 and b = intern_cell t2 in
  a == b   (* physical identity: both point to the same shared canonical node *)

(* Number of distinct cells currently shared (for diagnostics/measurement). *)
let interned_cell_count () = Hashtbl.length cell_intern_table

(* Debt 2: make generated cells observable. The desugar layer registers each
   geom_morphism's directed cell here by morphism name, so a surface query can
   inspect it. Cells are compile-time artifacts (alpha: no silicon payload), so
   "inspection" is a compile-time fact about the cell, not a runtime value. *)
let geom_cell_registry : (string, term) Hashtbl.t = Hashtbl.create 64

let reset_geom_cell_registry () = Hashtbl.reset geom_cell_registry

let register_geom_cell (name : string) (cell : term) : unit =
  Hashtbl.replace geom_cell_registry name cell

let lookup_geom_cell (name : string) : term option =
  Hashtbl.find_opt geom_cell_registry name

(* A human-readable rendering of a cell's directed boundary, for inspection:
   "c_src -> c_tgt" for an inclusion, or a tag for other shapes. *)
let describe_cell (t : term) : string =
  match t with
  | TmCoh (_, CellArr (s, tg, CellStar), _) ->
      let n x = (match x with TmVar nm -> nm | _ -> "?") in
      Printf.sprintf "directed 1-cell: %s -> %s" (n s) (n tg)
  | TmCoh (_, CellArr (_, _, CellArr _), _) -> "directed 2-cell"
  | TmId _ -> "identity cell (collapsed)"
  | TmVar v -> "0-cell: " ^ v
  | _ -> "cell"

(* ─── On-disk persistence of the cell graph (OCaml-side, no xleech2/C) ───────

   Persisting the proof/cell graph gives two benefits even on a single node
   (N=1, no network): incremental compilation (an unchanged sub-graph keeps the
   same serialized key, so its work can be skipped) and reusable O(1)
   verification. We serialize the CANONICAL form (parts 84-85, names already
   "#0","#1"...), so the same logical cell yields the same text on any machine,
   deterministically — the prerequisite the binder fix unlocked.

   Format: a deterministic textual S-expression of the canonical term. Textual
   (not Marshal) so it is inspectable and OCaml-version-independent. This writes
   from the compiler directly; it does NOT touch the C runtime arena (xleech2),
   which would require an OCaml<->C bridge and is only needed for cross-NODE wire
   payloads (the deferred distributed case). *)
let rec serialize_term (t : term) : string =
  match t with
  | TmVar x -> "(var " ^ x ^ ")"
  | TmId (t', c) ->
      "(id " ^ serialize_term t' ^ " " ^ serialize_cell c ^ ")"
  | TmCoh (ps, ty, sub) ->
      let ps_s =
        String.concat " "
          (List.map (fun (k, c) -> "(" ^ k ^ " " ^ serialize_cell c ^ ")") ps)
      in
      let sub_s =
        String.concat " "
          (List.map (fun (k, tm) -> "(" ^ k ^ " " ^ serialize_term tm ^ ")") sub)
      in
      "(coh [" ^ ps_s ^ "] " ^ serialize_cell ty ^ " [" ^ sub_s ^ "])"

and serialize_cell (c : cell) : string =
  match c with
  | CellStar -> "*"
  | CellArr (s, t, a) ->
      "(arr " ^ serialize_term s ^ " " ^ serialize_term t ^ " "
      ^ serialize_cell a ^ ")"

(* The persistent key of a cell: serialization of its canonical form. Two
   alpha-equivalent cells share this key exactly. *)
let cell_persist_key (t : term) : string = serialize_term (canonical_form t)

(* Write the registered geom-morphism cells to a file, one per line:
   "<morphism_name>\t<canonical_serialization>". Deterministic ordering (sorted
   by name) so the file itself is content-stable across runs. *)
let persist_geom_cells (path : string) : unit =
  let entries =
    Hashtbl.fold (fun name cell acc -> (name, cell_persist_key cell) :: acc)
      geom_cell_registry []
  in
  let entries = List.sort (fun (a, _) (b, _) -> compare a b) entries in
  let oc = open_out path in
  List.iter (fun (name, key) -> Printf.fprintf oc "%s\t%s\n" name key) entries;
  close_out oc

(* Load a persisted cell graph: returns (name -> canonical serialization) map.
   Used to detect unchanged sub-graphs (incremental compilation): if a cell's
   current key equals the persisted one, its work can be skipped. *)
let load_persisted_cells (path : string) : (string * string) list =
  if not (Sys.file_exists path) then []
  else begin
    let ic = open_in path in
    let rec loop acc =
      match input_line ic with
      | line ->
          (match String.index_opt line '\t' with
           | Some i ->
               let name = String.sub line 0 i in
               let key = String.sub line (i + 1) (String.length line - i - 1) in
               loop ((name, key) :: acc)
           | None -> loop acc)
      | exception End_of_file -> (try close_in ic with _ -> ()); List.rev acc
    in
    loop []
  end

(* ─── Incremental compilation loop (uses the persisted graph) ───────────────

   The persisted graph becomes useful when the compiler consults it: at startup
   we load the previous keys; for each cell, if its current canonical key equals
   the persisted one, the cell is UNCHANGED and its downstream work can be
   skipped. This is the N=1 incremental-compilation benefit, realized. *)
let incremental_prev : (string, string) Hashtbl.t = Hashtbl.create 64
let incremental_skips = ref 0
let incremental_checks = ref 0

let incremental_load (path : string) : unit =
  Hashtbl.reset incremental_prev;
  incremental_skips := 0;
  incremental_checks := 0;
  List.iter (fun (name, key) -> Hashtbl.replace incremental_prev name key)
    (load_persisted_cells path)

(* True if this cell is UNCHANGED vs the persisted graph (work skippable). *)
let incremental_unchanged (name : string) (cell : term) : bool =
  incr incremental_checks;
  match Hashtbl.find_opt incremental_prev name with
  | Some prev_key when prev_key = cell_persist_key cell ->
      incr incremental_skips; true
  | _ -> false

let incremental_stats () = (!incremental_skips, !incremental_checks)


(* ─── Family 2: beta-reduction ────────────────────────────────────────── *)

(* beta-reduction in the surface Yon language is handled by the kernel
 * Reduce module on Yon Core terms. At the CATT level, beta-like
 * reductions occur when a coherence is applied to a substitution
 * that names a coherence in turn:
 *
 *   coh_Gamma : A [σ]   where σ binds a variable to coh_Δ : B [τ]
 *
 * The reduction substitutes and may unfold the inner coherence. For
 * the prototype, we provide the structural beta-step that substitutes
 * a variable in a term. The full beta for CATT_R_Yon coheres at the
 * surface fun_decl level via the kernel.
 *)

let rec subst_in_term (t : term) (sub : subst) : term =
  match t with
  | TmVar x ->
      (match List.assoc_opt x sub with
       | Some replacement -> replacement
       | None -> t)
  | TmCoh (ps, ty, sub') ->
      (* The variables bound by ps are not in scope of the outer sub. *)
      let bound = List.map fst ps in
      let outer_sub = List.filter (fun (k, _) -> not (List.mem k bound)) sub in
      let sub'' = List.map (fun (k, v) -> (k, subst_in_term v outer_sub)) sub' in
      TmCoh (ps, ty, sub'')
  | TmId (t', c) -> TmId (subst_in_term t' sub, subst_in_cell c sub)

and subst_in_cell (c : cell) (sub : subst) : cell =
  match c with
  | CellStar -> CellStar
  | CellArr (s, t, a) ->
      CellArr (subst_in_term s sub, subst_in_term t sub, subst_in_cell a sub)

let family2_beta_step (t : term) (sub : subst) : term =
  subst_in_term t sub

(* ─── Family 3: η-equivalence ──────────────────────────────────────── *)

(* η in CATT: a coherence coh_Gamma : A [identity_sub] reduces to a simpler
 * form if its ps-context and substitution are trivial.
 *
 * For terms at the surface: a function lambdax. f(x) where x doesn't
 * appear in f is η-equivalent to f. The kernel handles this on
 * Yon Core. At the CATT level, we check whether a TmCoh has the
 * identity substitution and trivial ps_ctx, in which case it reduces
 * to the underlying body.
 *)

let is_identity_sub (sub : subst) (ps : ps_ctx) : bool =
  List.length sub = List.length ps
  && List.for_all2
       (fun (k1, v) (k2, _) -> k1 = k2 && (match v with TmVar n -> n = k1 | _ -> false))
       sub ps

let family3_eta_step (t : term) : term =
  match t with
  | TmCoh (ps, _ty, sub) when is_identity_sub sub ps ->
      (* η: identity coherence is the identity, reduces to the var.
       * But in our globular setting, what we return depends on the
       * pasting context. For a single-variable ps_ctx of a 0-cell,
       * the identity reduces to the variable itself. *)
      (match ps with
       | [(x, CellStar)] -> TmVar x
       | _ -> t)
  | _ -> t

(* ─── Family 4: Place equivalence by signature ─────────────────────── *)

(* Two places are equivalent under R_Yon Family 4 if they have the
 * same signature: same fields (with same types in same order) and
 * same operations (with same param/return signatures).
 *
 * This is what allows univalence-like reasoning at the place level:
 * if A and B are structurally identical places, programs that work
 * on A also work on B and vice versa.
 *)

let rec field_equiv (f1 : field_decl) (f2 : field_decl) : bool =
  f1.fd_name = f2.fd_name
  && ty_structural_eq f1.fd_ty f2.fd_ty

and op_equiv (o1 : operation_decl) (o2 : operation_decl) : bool =
  o1.op_name = o2.op_name
  && List.length o1.op_params = List.length o2.op_params
  && List.for_all2
       (fun p1 p2 -> ty_structural_eq p1.param_ty p2.param_ty)
       o1.op_params o2.op_params
  && (match o1.op_return, o2.op_return with
      | None, None -> true
      | Some t1, Some t2 -> ty_structural_eq t1 t2
      | _ -> false)

and ty_structural_eq (t1 : ty) (t2 : ty) : bool =
  let canon name =
    match name with
    | "boolean" | "proposition" -> "__bool_or_prop"
    | other -> other
  in
  (* "unknown" is a polymorphic placeholder used by stdlib signatures.
   * It unifies with any other type. Same for TyVar (true generic
   * binders from fun<A>). *)
  let is_unknown t =
    match t with
    | TyPrim "unknown" -> true
    | TyUser "unknown" -> true
    | TyVar _ -> true   (* generic binder unifies with anything *)
    | _ -> false
  in
  (* Legacy "Path" (cubical) is structurally an Id type. We accept
   * Path ↔ TyId _ as compatible to preserve backward compatibility
   * of pre-HoTT-promotion code. *)
  let is_path_alias t =
    match t with
    | TyUser "Path" | TyPrim "Path" -> true
    | _ -> false
  in
  let is_id_type t =
    match t with
    | TyId _ -> true
    | _ -> false
  in
  if is_unknown t1 || is_unknown t2 then true
  else if (is_path_alias t1 && is_id_type t2)
       || (is_path_alias t2 && is_id_type t1)
       || (is_path_alias t1 && is_path_alias t2)
  then true
  else
  match t1, t2 with
  | TyPrim n1, TyPrim n2 -> canon n1 = canon n2
  | TyPrim n1, TyPrimIn (n2, _) | TyPrimIn (n1, _), TyPrim n2 ->
      canon n1 = canon n2
  | TyPrimIn (n1, _), TyPrimIn (n2, _) -> canon n1 = canon n2
  | TyUser n1, TyUser n2 -> canon n1 = canon n2
  | TyUser n, TyPrim m | TyPrim n, TyUser m -> canon n = canon m
  | TyList a, TyList b -> ty_structural_eq a b
  | TyMap (k1, v1), TyMap (k2, v2) ->
      ty_structural_eq k1 k2 && ty_structural_eq v1 v2
  | TyStream (a, _), TyStream (b, _) -> ty_structural_eq a b
  | TySum vs1, TySum vs2 ->
      List.length vs1 = List.length vs2
      && List.for_all2 variant_eq vs1 vs2
  (* HoTT type equivalences with cumulative subtyping for universes. *)
  | TyUniverse n1, TyUniverse n2 ->
      (* Cumulativity: Type_n <: Type_m whenever n <= m.
       * Equivalence (used here as a coarse approximation of typing)
       * accepts when EITHER level can be lifted to match the other. *)
      n1 = n2 || n1 < n2 || n2 < n1  (* always true if both universes;
                                       * cumulative subtyping is symmetric
                                       * in the equivalence check. *)
  | TyPi (_x1, a1, b1), TyPi (_x2, a2, b2) ->
      (* Two Pi-types equivalent iff their domain and codomain are. *)
      ty_structural_eq a1 a2 && ty_structural_eq b1 b2
  | TySigma (_x1, a1, b1), TySigma (_x2, a2, b2) ->
      ty_structural_eq a1 a2 && ty_structural_eq b1 b2
  | TyId (a1, _, _), TyId (a2, _, _) ->
      (* Id types carry endpoint terms; we compare carriers structurally
       * and treat endpoints conservatively as equal. Full path equality
       * requires a homotopical comparison via J — beyond this layer. *)
      ty_structural_eq a1 a2
  | _, _ -> false

and variant_eq (v1 : variant) (v2 : variant) : bool =
  v1.v_name = v2.v_name
  && List.length v1.v_args = List.length v2.v_args
  && List.for_all2 ty_structural_eq v1.v_args v2.v_args

let family4_place_equiv (p1 : place_decl) (p2 : place_decl) : bool =
  let extract_fields p =
    List.filter_map (function FoField f -> Some f | FoOp _ -> None | FoCell _ -> None | FoLaw _ -> None) p.pd_members
  in
  let extract_ops p =
    List.filter_map (function FoOp o -> Some o | FoField _ -> None | FoCell _ -> None | FoLaw _ -> None) p.pd_members
  in
  let fs1 = extract_fields p1 and fs2 = extract_fields p2 in
  let ops1 = extract_ops p1 and ops2 = extract_ops p2 in
  List.length fs1 = List.length fs2
  && List.length ops1 = List.length ops2
  && List.for_all2 field_equiv fs1 fs2
  && List.for_all2 op_equiv ops1 ops2

(* ─── Family 4 (constructive): place isomorphism ───────────────
 *
 * Two places are *isomorphic* in the structure category when there
 * exists a bijective renaming of their fields/operations preserving
 * types. This generalizes family4_place_equiv (which required
 * positionally-aligned identity) to permit any reordering plus name
 * renaming.
 *
 * Yoneda perspective: an isomorphism of places is a 1-cell in the
 * 2-category of objects-with-structure that has a 2-sided inverse.
 * Constructively, we produce the bijection (the witness of the iso)
 * as a list of name pairs, then verify both directions are valid. *)

(* Find a bijection between two lists of fields up to type equivalence.
 * Returns Some [(n1, n2); ...] if a bijection exists, None otherwise.
 *
 * Algorithm: for each field in list1, find an unused field in list2
 * with compatible type, pair them. If at some step no candidate
 * exists, the overall iso fails. This is a greedy matching; for the
 * surface AST it suffices because field types are concrete enough
 * that ambiguity rarely matters. *)
let rec field_bijection (fs1 : field_decl list) (fs2 : field_decl list)
    : (string * string) list option =
  match fs1 with
  | [] -> if fs2 = [] then Some [] else None
  | f :: rest ->
      let rec try_match prefix = function
        | [] -> None
        | g :: tail when ty_structural_eq f.fd_ty g.fd_ty ->
            let remaining = prefix @ tail in
            (match field_bijection rest remaining with
             | Some sub -> Some ((f.fd_name, g.fd_name) :: sub)
             | None -> try_match (prefix @ [g]) tail)
        | g :: tail -> try_match (prefix @ [g]) tail
      in
      try_match [] fs2

(* Operation bijection: same idea but matches both name structure
 * (param count + return type) AND param types pointwise. *)
let rec op_bijection (ops1 : operation_decl list) (ops2 : operation_decl list)
    : (string * string) list option =
  let op_compatible (o1 : operation_decl) (o2 : operation_decl) =
    List.length o1.op_params = List.length o2.op_params
    && List.for_all2
         (fun p1 p2 -> ty_structural_eq p1.param_ty p2.param_ty)
         o1.op_params o2.op_params
    && (match o1.op_return, o2.op_return with
        | Some r1, Some r2 -> ty_structural_eq r1 r2
        | None, None -> true
        | _ -> false)
  in
  match ops1 with
  | [] -> if ops2 = [] then Some [] else None
  | o :: rest ->
      let rec try_match prefix = function
        | [] -> None
        | g :: tail when op_compatible o g ->
            let remaining = prefix @ tail in
            (match op_bijection rest remaining with
             | Some sub -> Some ((o.op_name, g.op_name) :: sub)
             | None -> try_match (prefix @ [g]) tail)
        | g :: tail -> try_match (prefix @ [g]) tail
      in
      try_match [] ops1

(* The full place isomorphism: produces a witness (field_iso, op_iso)
 * when the two places have compatible structure. Returns None when
 * no bijection exists. *)
let place_isomorphism (p1 : place_decl) (p2 : place_decl)
    : ((string * string) list * (string * string) list) option =
  let extract_fields p =
    List.filter_map (function FoField f -> Some f | FoOp _ -> None | FoCell _ -> None | FoLaw _ -> None) p.pd_members
  in
  let extract_ops p =
    List.filter_map (function FoOp o -> Some o | FoField _ -> None | FoCell _ -> None | FoLaw _ -> None) p.pd_members
  in
  let fs1 = extract_fields p1 and fs2 = extract_fields p2 in
  let ops1 = extract_ops p1 and ops2 = extract_ops p2 in
  match field_bijection fs1 fs2, op_bijection ops1 ops2 with
  | Some fi, Some oi -> Some (fi, oi)
  | _ -> None

(* Yoneda-coherent place equivalence: two places are equivalent iff
 * there's an isomorphism between them. *)
let family4_place_iso (p1 : place_decl) (p2 : place_decl) : bool =
  place_isomorphism p1 p2 <> None

(* ─── Family 5 (constructive): Eckmann-Hilton swap ────────────
 *
 * In an omega-category, for two 2-cells alpha, beta : id_x ==> id_x on the
 * identity 1-cell at x, the interchange law forces:
 *
 *   alpha o_h beta = alpha o_v beta = beta o_v alpha = beta o_h alpha
 *
 * where o_h is horizontal composition and o_v is vertical. This is
 * the Eckmann-Hilton argument: any monoid structure on End(id_x)
 * with two compatible operations is commutative.
 *
 * The EH swap is the 3-cell witnessing alpha o_h beta = beta o_h alpha — it lives
 * in dimension 3 (one above the 2-cells it relates).
 *
 * Pasting scheme:
 *   [x : star, ix : x -> x = id_x,
 *    alpha : ix ==> ix, beta : ix ==> ix]
 *
 * The 3-cell is between (alpha o_h beta) and (beta o_h alpha), both 2-cells. *)

let ps_eckmann_hilton : ps_ctx = [
  ("x", CellStar);
  ("ix", CellArr (TmVar "x", TmVar "x", CellStar));  (* id-like 1-cell *)
  ("alpha", CellArr (TmVar "ix", TmVar "ix",
                     CellArr (TmVar "x", TmVar "x", CellStar)));
  ("beta", CellArr (TmVar "ix", TmVar "ix",
                    CellArr (TmVar "x", TmVar "x", CellStar)));
]

(* Build the Eckmann-Hilton swap witness. *)
let eckmann_hilton_swap (x : term) : term =
  let ix_cell = CellArr (x, x, CellStar) in  (* the identity 1-cell *)
  let two_cell_base = ix_cell in              (* 2-cells live over this *)
  let two_cell_type = CellArr (TmVar "ix", TmVar "ix", two_cell_base) in
  (* alpha o_h beta and beta o_h alpha are both 2-cells; the EH swap is the 3-cell
   * between them. *)
  let alpha_h_beta = TmVar "__alpha_h_beta" in
  let beta_h_alpha = TmVar "__beta_h_alpha" in
  let swap_cell = CellArr (alpha_h_beta, beta_h_alpha, two_cell_type) in
  TmCoh (ps_eckmann_hilton, swap_cell,
         [("x", x);
          ("ix", TmId (x, CellStar));
          ("alpha", TmVar "__alpha");
          ("beta", TmVar "__beta")])

(* Test entry: the EH swap should be a 3-cell whose base is the
 * 2-cell type alpha : id_x ==> id_x (and likewise for beta). *)
let test_eckmann_hilton () =
  let x = TmVar "x" in
  let swap = eckmann_hilton_swap x in
  match swap with
  | TmCoh (_, CellArr (_alpha_beta, _beta_alpha, two_cell_type), _) ->
      (* two_cell_type is CellArr(ix, ix, CellArr(x, x, CellStar)) *)
      (match two_cell_type with
       | CellArr (_, _, CellArr (s, t, CellStar)) ->
           alpha_equiv_term s x [] && alpha_equiv_term t x []
       | _ -> false)
  | _ -> false

(* ─── Family 6 (constructive): pasting diagrams as terms ─────
 *
 * The ps_ctx type above is the *linear telescope* representation: a
 * flat list of named cells. Batanin-Maltsiniotis give the general
 * definition: pasting diagrams are terms in a globular operad,
 * generated by:
 *
 *   - disk_n     : the free n-cell (n >= 0)
 *   - paste      : compose two diagrams along their boundary
 *   - suspend    : lift a diagram one dimension up
 *
 * Below we encode this as an inductive type. *)

type pasting_diagram =
  | PDisk of int                              (* disk_n, the free n-cell *)
  | PPaste of pasting_diagram * pasting_diagram * int
                                              (* paste two diagrams at dim k *)
  | PSuspend of pasting_diagram               (* suspend (raise dim by 1) *)

let rec pd_dim (d : pasting_diagram) : int =
  match d with
  | PDisk n -> n
  | PPaste (d1, d2, _) -> max (pd_dim d1) (pd_dim d2)
  | PSuspend d -> pd_dim d + 1

let rec pd_valid (d : pasting_diagram) : bool =
  match d with
  | PDisk n -> n >= 0
  | PPaste (d1, d2, k) ->
      pd_valid d1 && pd_valid d2
      && pd_dim d1 > k && pd_dim d2 > k
  | PSuspend d -> pd_valid d

let rec flatten_to_ps_ctx (d : pasting_diagram) (prefix : string) : ps_ctx =
  match d with
  | PDisk 0 -> [(prefix ^ "x", CellStar)]
  | PDisk n ->
      let objs = List.init (n + 1)
        (fun i -> (Printf.sprintf "%sx%d" prefix i, CellStar)) in
      let arrs = List.init n
        (fun i ->
           let src = TmVar (Printf.sprintf "%sx%d" prefix i) in
           let tgt = TmVar (Printf.sprintf "%sx%d" prefix (i + 1)) in
           (Printf.sprintf "%sf%d" prefix i,
            CellArr (src, tgt, CellStar))) in
      objs @ arrs
  | PPaste (d1, d2, _k) ->
      let left = flatten_to_ps_ctx d1 (prefix ^ "L") in
      let right = flatten_to_ps_ctx d2 (prefix ^ "R") in
      left @ right
  | PSuspend d ->
      let inner = flatten_to_ps_ctx d (prefix ^ "S") in
      let new_endpoints = [
        (prefix ^ "north", CellStar);
        (prefix ^ "south", CellStar);
      ] in
      new_endpoints @ inner

