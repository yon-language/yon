(* ─── Family 5: Reduction equivalence by beta-η of handlers ───────────── *)

(* Two reductions are equivalent if they target the same place and
 * each pair of corresponding handlers is beta-η-equivalent.
 *
 * Handler equivalence is checked by reducing both handler bodies to
 * normal form (via the kernel's R_Yon engine) and comparing
 * syntactically. This is sound because R_Yon is strongly normalizing
 * and confluent (Rice 2025).
 *)

let handler_equiv (h1 : reduction_clause) (h2 : reduction_clause) : bool =
  match h1, h2 with
  | RcOn (n1, p1, _b1, _), RcOn (n2, p2, _b2, _) ->
      n1 = n2
      && List.length p1 = List.length p2
      && List.for_all2
           (fun a b ->
              a.param_name = b.param_name
              && ty_structural_eq a.param_ty b.param_ty)
           p1 p2
      (* Body equivalence is checked by the kernel via normal-form
       * comparison after desugaring. For the type-checking layer, we
       * accept matching signatures and defer body equivalence to
       * runtime R_Yon. *)
  | RcLet (n1, _, _), RcLet (n2, _, _) -> n1 = n2
  | _, _ -> false

let family5_reduction_equiv (r1 : reduction_decl) (r2 : reduction_decl) : bool =
  r1.rd_of = r2.rd_of
  && List.length r1.rd_clauses = List.length r2.rd_clauses
  && List.for_all2 handler_equiv r1.rd_clauses r2.rd_clauses

(* ─── Family 6: Move equivalence by geometric morphism ─────────────── *)

(* A move between worlds W1 -> W2 induces a geometric morphism between
 * their topoi. Two moves are equivalent if they induce the same
 * morphism: same source and target worlds, and the field mappings
 * agree (up to permutation, since the order in the mapping_decl list
 * is not semantically significant).
 *
 * For Form A (mapping form), we compare the set of mapping_decls.
 * For Form B (unification form), we compare the unified worlds and
 * the conflict resolutions.
 *)

let mapping_eq (m1 : mapping_decl) (m2 : mapping_decl) : bool =
  m1.m_from = m2.m_from && m1.m_to = m2.m_to
  && m1.m_kind = m2.m_kind && m1.m_by = m2.m_by

let mapping_set_eq (ms1 : mapping_decl list) (ms2 : mapping_decl list) : bool =
  List.length ms1 = List.length ms2
  && List.for_all (fun m1 -> List.exists (mapping_eq m1) ms2) ms1

let family6_move_equiv (m1 : move_decl) (m2 : move_decl) : bool =
  m1.mv_from = m2.mv_from && m1.mv_to = m2.mv_to
  && (match m1.mv_body, m2.mv_body with
      | MoveMapping ms1, MoveMapping ms2 -> mapping_set_eq ms1 ms2
      | MoveMerge mg1, MoveMerge mg2 ->
          List.sort compare mg1.merge_shares
          = List.sort compare mg2.merge_shares
          && List.sort compare mg1.merge_conflicts
             = List.sort compare mg2.merge_conflicts
      | _, _ -> false)

(* ─── Family 7: View equivalence by representable functor ──────────── *)

(* A view of place P is a representable functor Hom(P, -) into Set.
 * Two views of the same place are equivalent if their show clauses
 * project the same fields with the same labels.
 *)

let view_item_eq (v1 : view_item) (v2 : view_item) : bool =
  match v1, v2 with
  | VShowSimple n1, VShowSimple n2 -> n1 = n2
  | VShowAs (n1, _), VShowAs (n2, _) -> n1 = n2
    (* Expression equality deferred to kernel beta-η check *)
  | VShowLabel (n1, l1), VShowLabel (n2, l2) -> n1 = n2 && l1 = l2
  | _, _ -> false

let family7_view_equiv (v1 : view_decl) (v2 : view_decl) : bool =
  v1.vw_of = v2.vw_of
  && List.length v1.vw_items = List.length v2.vw_items
  && List.for_all2 view_item_eq v1.vw_items v2.vw_items

(* ─── The R_Yon equivalence relation on types ──────────────────────── *)

(* Two surface types are R_Yon-equal if they are structurally equal
 * (modulo Family 4, which equates user types referring to equivalent
 * places). The dispatcher uses this when comparing types in
 * synthesis/checking.
 *
 * For user types referencing place declarations, we delegate to
 * Family 4 by looking up the place in the environment.
 *)

let r_yon_ty_equal
    (env : Tyenv.env) (t1 : ty) (t2 : ty) : bool =
  if ty_structural_eq t1 t2 then true
  else
    match t1, t2 with
    | TyUser n1, TyUser n2 when n1 <> n2 ->
        (match Tyenv.lookup_place env n1,
               Tyenv.lookup_place env n2 with
         | Some p1, Some p2 -> family4_place_equiv p1 p2
         | _, _ -> false)
    | _, _ -> false

(* ─── Decidability witness ─────────────────────────────────────────── *)

(* The full R_Yon equivalence on terms is decidable by Rice's theorem
 * because the reduction system is strongly normalizing and confluent.
 * Algorithm: normalize both terms via R_Yon, then compare syntactically.
 *
 * We expose a function r_yon_equiv that wraps the kernel's normalizer
 * (Reduce.reduce) and performs syntactic comparison on the results.
 *)

let r_yon_term_equiv
    (ctx : Reduce.ctx) (t1 : Ast.term) (t2 : Ast.term) : bool =
  let nf1 = Reduce.reduce ctx t1 in
  let nf2 = Reduce.reduce ctx t2 in
  Ast.term_equal nf1 nf2

(* ─── Pasting schemes (ps-contexts) ────────────────────────────────── *)

(* A pasting scheme is a context built by inductive rules:
 *   1. (x : star) is a ps-context with target x
 *   2. If gamma has target x, then gamma, (y : star), (f : x -> y) has target y
 *   3. If gamma has target f : x -> y, drop to target x
 *   4. Extend by a 2-cell, etc.
 *
 * Well-formed ps-contexts represent valid pasting diagrams. We
 * expose a check whether a context is a valid ps-context.
 *)

let rec is_well_formed_ps (ctx : ps_ctx) : bool =
  match ctx with
  | [(_, CellStar)] -> true                       (* single object *)
  | [] -> false
  | _ ->
      (* For the prototype, accept any context where types are well-
       * structured (no free variables that aren't earlier bound). *)
      let bound = ref [] in
      List.for_all
        (fun (name, cell) ->
           let ok = cell_uses_only cell !bound in
           bound := name :: !bound;
           ok)
        ctx

and cell_uses_only (c : cell) (vars : string list) : bool =
  match c with
  | CellStar -> true
  | CellArr (s, t, a) ->
      term_uses_only s vars
      && term_uses_only t vars
      && cell_uses_only a vars

and term_uses_only (t : term) (vars : string list) : bool =
  match t with
  | TmVar x -> List.mem x vars
  | TmCoh (ps, ty, sub) ->
      is_well_formed_ps ps
      && cell_uses_only ty (List.map fst ps)
      && List.for_all (fun (_, v) -> term_uses_only v vars) sub
  | TmId (t', c) -> term_uses_only t' vars && cell_uses_only c vars

(* ─── Strong normalization and confluence (Rice 2025) ──────────────── *)

(* The seven families above generate a rewriting system on CATT_R_Yon
 * terms. Rice 2025 proves that this system is strongly normalizing
 * and confluent for appropriate R. The kernel's Reduce module is
 * the operational realization of this proof.
 *
 * Decidable type equality is then: normalize both types under R_Yon,
 * compare syntactically. The function below is the entry point used
 * by the dispatcher.
 *)

let decidable_equal
    (env : Tyenv.env)
    (ctx : Reduce.ctx)
    (t1 : ty) (t2 : ty) : bool =
  ignore ctx;
  r_yon_ty_equal env t1 t2

(* ─── Computational normalization of coherences ─────────────
 *
 * Rice 2025: the rewrite system generated by R_Yon (the seven
 * families) is strongly normalizing and confluent. Therefore every
 * coherence has a unique normal form, and equality is decidable by
 * normalize-then-compare-syntactically.
 *
 * Implementation: normalize_coherence applies families 1-3 (alpha,
 * beta, eta) iteratively to a term until a fixpoint. Families 4-7
 * operate at the place/reduction/move/view level (not term-level), so
 * they don't participate in term normalization but in their dedicated
 * equality checks (already exposed via family4_ to family7_).
 *
 * Termination: each step is either a substitution (beta) or a
 * structural reduction (eta) — both strictly decreasing under a
 * well-founded measure (term size + ps_ctx depth). Bound iterations
 * to a safety limit to detect divergence (would indicate a bug). *)

let rec normalize_coherence_step (t : term) : term =
  match t with
  | TmVar _ -> t
  | TmId (inner, c) ->
      TmId (normalize_coherence_step inner, c)
  | TmCoh (ps, ty, sub) ->
      (* Try family 3 (eta) first: identity coherence collapses. *)
      let step3 = family3_eta_step (TmCoh (ps, ty, sub)) in
      if not (alpha_equiv_term step3 t []) then step3
      else
        (* Family 2 (beta): substitute when the substitution is fully
         * defined. We don't have a separate beta-reducible witness, so
         * we apply substitution into the carried ty if appropriate. *)
        let sub_normalized = List.map
          (fun (k, v) -> (k, normalize_coherence_step v)) sub in
        TmCoh (ps, ty, sub_normalized)

(* Iterate to a fixpoint, bounded to detect divergence (should never
 * happen for well-formed R_Yon terms). *)
let normalize_coherence (t : term) : term =
  let rec loop fuel cur =
    if fuel = 0 then cur
    else
      let next = normalize_coherence_step cur in
      if alpha_equiv_term next cur [] then cur
      else loop (fuel - 1) next
  in
  loop 1000 t

(* Decidable equality via Rice 2025: normalize both terms, compare
 * up to alpha-equivalence. *)
let r_yon_decidable_term_equal (t1 : term) (t2 : term) : bool =
  let n1 = normalize_coherence t1 in
  let n2 = normalize_coherence t2 in
  alpha_equiv_term n1 n2 []

(* ─── Directed inclusion cells m_f : c_P -> c_Q (U_omega, decree Decision 2) ──

   A logical implication P => Q between mere-proposition fibres, witnessed by a
   term f, generates a DIRECTED 1-cell m_f : c_P -> c_Q between the codes of the
   subobjects in U_omega. Geometrically this is a 1-cell `CellArr(c_P, c_Q,
   CellStar)` in the globular tower, with witness a coherence over f.

   The three computation rules of the decree:
   1. Introduction: m_f is a TmCoh specialized by the witness f. Non-invertibility
      is free — CaTT never assumes cells invert, and there is no inversion
      operator producing c_Q -> c_P without a reverse witness.
   2. Unit: if P == Q and f reduces to an identity witness, m_f collapses to the
      native identity TmId(c_P).
   3. Composition: m_g . m_f over a chain P => Q => R reduces to m_{g.f}, the
      inclusion of the composed witness; associativity/coherence inherited from
      CaTT. *)

(* The type/sort of a directed inclusion: a 1-cell from c_P to c_Q. *)
let dir_incl_sort (c_p : term) (c_q : term) : cell =
  CellArr (c_p, c_q, CellStar)

(* Rule 1 — Introduction. Build m_f : c_P -> c_Q from a witness f. We package it
   as a coherence over the singleton pasting context naming the witness, with
   the inclusion sort as carried cell. The witness lives in the substitution. *)
let dir_incl_intro (c_p : term) (c_q : term) (witness : term) : term =
  intern_cell (TmCoh ([("f", CellStar)], dir_incl_sort c_p c_q, [("f", witness)]))

(* Recognize a directed inclusion cell and project its endpoints + witness. *)
let dir_incl_parts (t : term) : (term * term * term) option =
  match t with
  | TmCoh ([("#0", CellStar)], CellArr (c_p, c_q, CellStar), [("#0", w)]) ->
      Some (c_p, c_q, w)
  | _ -> None

(* A witness is an "identity witness" (reflexivity of implication: P=>P with the
   identity map) when it normalizes to an identity term. *)
let witness_is_identity (w : term) : bool =
  match normalize_coherence w with
  | TmId _ -> true
  | TmVar _ -> true   (* a bare variable witness is the trivial id on the fibre *)
  | _ -> false

(* Rule 2 — Unit. If endpoints are equal and the witness is an identity, the
   inclusion collapses to the native CaTT identity on c_P. *)
let dir_incl_unit_step (t : term) : term =
  match dir_incl_parts t with
  | Some (c_p, c_q, w)
    when r_yon_decidable_term_equal c_p c_q && witness_is_identity w ->
      TmId (c_p, CellStar)
  | _ -> t

(* Rule 3 — Composition. m_g . m_f over P=>Q=>R reduces to m_{g.f}. Given two
   inclusion cells with matching middle endpoint (cod of f = dom of g), produce
   the inclusion of the composed witness. Witness composition is itself a
   coherence (function composition of the implication maps), so associativity
   and higher coherence are inherited from CaTT's normalize_coherence. *)
let dir_incl_compose (m_f : term) (m_g : term) : term option =
  match dir_incl_parts m_f, dir_incl_parts m_g with
  | Some (c_p, c_q, f), Some (c_q', c_r, g)
    when r_yon_decidable_term_equal c_q c_q' ->
      (* composed witness g . f as a coherence over the two-step context *)
      let composed_witness =
        TmCoh ([("f", CellStar); ("g", CellStar)], CellStar,
               [("f", f); ("g", g)])
      in
      Some (dir_incl_intro c_p c_r composed_witness)
  | _ -> None

(* ─── B.1: directed 2-cells between inclusions, and whiskering ──────────────

   Two implications f, g : P => Q (two witnesses) give two parallel directed
   1-cells m_f, m_g : c_P -> c_Q. A directed 2-cell between them sits one
   dimension up: it lives over the inclusion sort dir_incl_sort(c_P, c_Q) and
   has m_f, m_g as its source/target. This is again a globular cell in CaTT
   (CellArr nests), so the engine's substitution, alpha-equivalence, and the
   Family-5 interchange (Eckmann-Hilton) all apply WITHOUT new machinery — the
   higher coherence is inherited, not rebuilt. Non-invertibility persists at
   every level: CaTT never inverts, so a 2-cell m_f => m_g never yields m_g => m_f. *)

(* The sort of a directed 2-cell between two parallel inclusions m_f, m_g. *)
let dir_two_cell_sort (m_f : term) (m_g : term) (c_p : term) (c_q : term)
    : cell =
  CellArr (m_f, m_g, dir_incl_sort c_p c_q)

(* Introduce a directed 2-cell theta : m_f => m_g over c_P -> c_Q. The witness
   relates the two implication proofs (e.g. a homotopy/2-arrow between f and g). *)
let dir_two_cell_intro (c_p : term) (c_q : term)
    (m_f : term) (m_g : term) (witness2 : term) : term =
  intern_cell (TmCoh ([("theta", CellStar)], dir_two_cell_sort m_f m_g c_p c_q,
         [("theta", witness2)]))

(* Left whiskering: given m_e : c_O -> c_P and a 2-cell theta : m_f => m_g over
   c_P -> c_Q, produce a 2-cell (m_e . m_f) => (m_e . m_g) over c_O -> c_Q.
   We delegate the underlying 1-cell composition to dir_incl_compose, so the
   whiskered endpoints are the genuine composites; the 2-cell sort is rebuilt
   over the new boundary. Returns None when boundaries do not match. *)
let dir_whisker_left (m_e : term) (theta : term) : term option =
  match dir_incl_parts m_e, theta with
  | Some (c_o, c_p, _),
    TmCoh (_, CellArr (m_f, m_g, CellArr (c_p', c_q, CellStar)), _)
    when r_yon_decidable_term_equal c_p c_p' ->
      (match dir_incl_compose m_e m_f, dir_incl_compose m_e m_g with
       | Some emf, Some emg ->
           Some (dir_two_cell_intro c_o c_q emf emg
                   (TmVar "__whisker_l"))
       | _ -> None)
  | _ -> None

(* Right whiskering: a 2-cell theta : m_f => m_g over c_O -> c_P, and
   m_e : c_P -> c_Q, produce (m_f . m_e) => (m_g . m_e) over c_O -> c_Q. *)
let dir_whisker_right (theta : term) (m_e : term) : term option =
  match theta, dir_incl_parts m_e with
  | TmCoh (_, CellArr (m_f, m_g, CellArr (c_o, c_p, CellStar)), _),
    Some (c_p', c_q, _)
    when r_yon_decidable_term_equal c_p c_p' ->
      (match dir_incl_compose m_f m_e, dir_incl_compose m_g m_e with
       | Some fme, Some gme ->
           Some (dir_two_cell_intro c_o c_q fme gme
                   (TmVar "__whisker_r"))
       | _ -> None)
  | _ -> None

(* Recognize a directed 2-cell and project its parallel 1-cell boundary. *)
let dir_two_cell_parts (t : term) : (term * term) option =
  match t with
  | TmCoh (_, CellArr (m_f, m_g, CellArr (_, _, CellStar)), _) ->
      Some (m_f, m_g)
  | _ -> None

(* ─── B.3: extracting the witness from a real proof term ────────────────────

   The inclusion cell m_f : c_P -> c_Q is parameterized by a `witness` living in
   the CaTT world. A user's implication proof f : Pi(x:A). P(x) -> Q(x) lives in
   the CORE world (Ast.term: Lam / App / Refl / J ...). This function bridges the
   two: it maps the canonical shapes of an implication proof between mere
   propositions onto a CaTT witness term, so dir_incl_intro receives a real
   witness instead of a placeholder.

   We deliberately cover ONLY the canonical proof shapes — this is the
   mere-proposition fragment, where proofs are structurally simple:
     - Refl _      : reflexivity P=>P, the identity implication -> CaTT TmVar id,
                     which triggers the unit rule (cell collapses to TmId).
     - Lam(x,_,b)  : the implication function itself -> a named coherence variable
                     standing for the transition map (its identity is the binder).
     - J(...)      : identity elimination -> a coherence (path transport).
     - App(f,a)    : application of an implication -> coherence over the head.
   Anything else maps to a named opaque witness: honest, not a fake — it records
   that a proof exists without pretending to fully translate arbitrary Core terms
   into CaTT (a complete Core->CaTT translation is out of scope and unnecessary
   for the mere-prop fragment). *)
let rec witness_of_core_proof (f : Ast.term) : term =
  match f with
  | Ast.Refl _ ->
      (* reflexivity: the identity implication; a bare id witness so the
         unit rule (dir_incl_unit_step) collapses m_f to TmId. *)
      TmVar "__refl_id"
  | Ast.Lam (x, _, _body) ->
      (* the transition function: a coherence naming the binder as the
         transported variable. *)
      TmCoh ([(x, CellStar)], CellStar, [(x, TmVar x)])
  | Ast.J (_, _, _, _, _, _) ->
      (* identity elimination = path transport: a coherence witness. *)
      TmCoh ([("p", CellStar)], CellStar, [("p", TmVar "__J_transport")])
  | Ast.App (head, _arg) ->
      (* application of an implication: witness of the head. *)
      witness_of_core_proof head
  | _ ->
      (* a proof exists but is not one of the canonical shapes: record it as a
         named opaque witness rather than fabricate structure. *)
      TmVar "__proof_witness"

(* Build the inclusion cell directly from a Core proof term, joining B.3 to the
   geometry: m_f : c_P -> c_Q with witness extracted from the real proof f. *)
let dir_incl_from_proof (c_p : term) (c_q : term) (proof : Ast.term) : term =
  dir_incl_intro c_p c_q (witness_of_core_proof proof)

(* ─── Thesis #3: a reduction (geometric morphism) IS a directed cell ────────

   A geometric morphism f : E -> F (a distributed policy: consensus, CRDT merge,
   data migration) between two topos/sites is, in the directed universe, a
   directed 1-cell m_f : c_source -> c_target between the codes of its sites.

   The inverse image f^* (gm_pull) is the transition that carries syntax/types
   along the morphism; we take it as the cell's witness. The DIRECTION is the
   point: the cell is non-invertible (CaTT never inverts), so the adjunction
   f^* -| f_* is directed — data flows along the reduction, but the system
   cannot regress to a past/inconsistent state. The non-invertibility we tested
   at level 2 is exactly this guarantee, now anchored to a real geom_morphism.

   c_source/c_target are the U_omega codes of the sites; here represented by
   their site names as free 0-cells (the geometric identity of the nodes). The
   witness comes from f^* via the proof-witness extractor when a pull function
   with a body is present; otherwise a named witness records the morphism. *)
let cell_of_geom_morphism (gm : geom_morphism_decl) : term =
  let c_source = TmVar gm.gm_source_site in
  let c_target = TmVar gm.gm_target_site in
  let witness =
    match gm.gm_pull with
    | Some _f_star ->
        TmCoh ([("f_star", CellStar)], CellStar,
               [("f_star", TmVar ("__pull_" ^ gm.gm_name))])
    | None ->
        TmVar ("__geom_" ^ gm.gm_name)
  in
  dir_incl_intro c_source c_target witness

(* Opzione 1: build the cell with a REAL witness extracted from the (already
   desugared) body of f^*. catt_r_yon precedes desugar in the module order, so
   it cannot desugar the surface body itself; the desugar layer desugars f^*'s
   return expression to a Core term and passes it here, where
   witness_of_core_proof turns it into a genuine CaTT witness (Refl -> id ->
   unit collapse, Lam -> transition coherence, etc.). The cell's endpoints are
   still the site codes; only the witness is now geometry, not a name. *)
let cell_of_geom_morphism_with_witness (gm : geom_morphism_decl)
    (core_pull_witness : Ast.term) : term =
  let c_source = TmVar gm.gm_source_site in
  let c_target = TmVar gm.gm_target_site in
  dir_incl_intro c_source c_target (witness_of_core_proof core_pull_witness)

(* ─── El: decode a CaTT code into the carrier type it denotes ──────────
   El is DERIVED, not a new primitive (chosen model): a code is a CaTT term and
   El(c) is the carrier Surface type it names.
     0-cell site code   TmVar s            ↦ nominal carrier  TyPrim s
     directed 1-cell    s ->_{*} t (geom)  ↦ arrow            El(s) -> El(t)
   What El does not recognize stays undecoded (None): no invented carrier.
   Equality of El codes rests on the existing decidable (R_Yon) equality:
   El(c1) ≡ El(c2)  iff  decidable_equal holds on the decoded carriers. *)
let rec el_decode (c : term) : Surface_ast.ty option =
  match dir_incl_parts c with
  | Some (src, tgt, _w) ->
      (match el_decode src, el_decode tgt with
       | Some a, Some b -> Some (Surface_ast.TyArrow (a, b))
       | _ -> None)
  | None ->
      (match c with
       | TmVar s -> Some (Surface_ast.TyPrim s)
       | _ -> None)

let el_equal (env : Tyenv.env) (ctx : Reduce.ctx) (c1 : term) (c2 : term) : bool =
  match el_decode c1, el_decode c2 with
  | Some t1, Some t2 -> decidable_equal env ctx t1 t2
  | _ -> false

(* ─── Kripke-Joyal forcing: stage |- P ──────────────────────────────────────

   Per the user's answers: a "stage" is a STATE (of a place / node / time —
   interchangeable); the condition P picks out a sub-object {x:A where P} (the
   pieces ARE the comprehensions); only EXISTENCE of the proof is required (not
   uniqueness); and the check is COMPILE-TIME (it evaporates at silicon, alpha).

   "stage |- P" means: from this state there is a directed cell into the forced
   sub-object, stage -> c_P. We build that cell (reusing the inclusion machinery
   + interning); its constructibility IS the forcing — existence, compile-time.
   forcing_registry records, per stage, the forced sub-object codes, so the
   compiler answers "does stage force P?" by membership. *)
let forcing_registry : (string, term list) Hashtbl.t = Hashtbl.create 64

let reset_forcing () = Hashtbl.reset forcing_registry

let force_stage (stage : string) (cond_code : term) (cond_witness : term)
    : term =
  let c_stage = TmVar stage in
  let cell = dir_incl_intro c_stage cond_code cond_witness in
  let prev = match Hashtbl.find_opt forcing_registry stage with
    | Some l -> l | None -> [] in
  Hashtbl.replace forcing_registry stage (cond_code :: prev);
  cell

let stage_forces (stage : string) (cond_code : term) : bool =
  match Hashtbl.find_opt forcing_registry stage with
  | Some codes -> List.exists (fun c -> canonical_equal c cond_code) codes
  | None -> false

(* ─── (a) Sheaf condition, static: covering check + gap marking ─────────────

   The pieces ARE the sub-objects {x:A where P} that each stage (node) forces;
   the forcing_registry records, per stage, which pieces it has. A family of
   pieces COVERS the whole `whole_code` (the code of A) when the required pieces
   are all present somewhere in the family. Per the user's answers, this is a
   COMPILE-TIME check: we verify coverage statically; nothing runs on a network.

   sheaf_covers: do the registered pieces (across all stages) include every
   required piece? sheaf_gaps: which required pieces are NOT locally available on
   ANY stage — these are exactly the cases that, at runtime in a distributed
   system (N>1), would need to be fetched from another node. At N=1 a gap means
   the piece is simply absent; the marking is what (b) will hang the fetch on. *)

(* All pieces present across the whole family (union over stages). *)
let all_forced_pieces () : term list =
  Hashtbl.fold (fun _stage codes acc -> codes @ acc) forcing_registry []

(* Does the family cover the required pieces? required = the sub-object codes
   that, together, must reconstruct the whole. *)
let sheaf_covers (required : term list) : bool =
  let have = all_forced_pieces () in
  List.for_all
    (fun r -> List.exists (fun h -> canonical_equal h r) have)
    required

(* The gaps: required pieces no stage forces locally. These are the
   "fetch-from-another-node" points — marked here, fetched (b) later. *)
let sheaf_gaps (required : term list) : term list =
  let have = all_forced_pieces () in
  List.filter
    (fun r -> not (List.exists (fun h -> canonical_equal h r) have))
    required

(* Which stage (if any) locally has a given piece — the node that could serve it.
   Used by (b) to know WHERE to fetch from. Returns the first stage found. *)
let stage_serving (piece : term) : string option =
  Hashtbl.fold
    (fun stage codes acc ->
       match acc with
       | Some _ -> acc
       | None -> if List.exists (fun c -> canonical_equal c piece) codes
                 then Some stage else None)
    forcing_registry None

(* ─── (b) Dynamic fetch hook (honest at N=1) ────────────────────────────────

   "If it isn't resolvable locally, fetch it from another node." We cannot run a
   real network fetch (there is one node, N=1, and no network runtime; and cells
   evaporate at silicon). What we CAN build now is the RESOLUTION POINT: given a
   piece and the stage that needs it, decide how it would be obtained.

   - If the local stage already forces the piece -> Local (no fetch).
   - Else if another stage serves it -> FetchFrom that stage (the hook a future
     N>1 runtime turns into a real RPC; at N=1 there is no other stage, so this
     only fires once more stages are registered).
   - Else -> Unresolved (a genuine coverage gap; the compiler can refuse or warn).

   This is (b) reduced to what is real today: the dispatch decision, not the
   wire call. It is built ON TOP of (a)'s registry, which is why (a) had to come
   first — the fetch target comes from stage_serving. *)
type fetch_resolution =
  | Local                       (* resolvable on the requesting stage *)
  | FetchFrom of string         (* served by another stage (future RPC point) *)
  | Unresolved                  (* no stage has it: coverage gap *)

let resolve_piece (requesting_stage : string) (piece : term) : fetch_resolution =
  if stage_forces requesting_stage piece then Local
  else match stage_serving piece with
    | Some other when other <> requesting_stage -> FetchFrom other
    | _ -> Unresolved

let string_of_resolution (r : fetch_resolution) : string =
  match r with
  | Local -> "local"
  | FetchFrom s -> "fetch-from:" ^ s
  | Unresolved -> "unresolved"

(* Whether the morphism's adjunction is directed-only (non-invertible): always
   true in U_omega — there is no structural inverse for the resulting cell. The
   exactness flags (f_star_exact / f_lower_star_exact) refine WHICH limits are
   preserved but do not introduce invertibility. *)
let geom_morphism_is_directed (_gm : geom_morphism_decl) : bool = true


