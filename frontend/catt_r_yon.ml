(* ─── Family 1 (constructive): cell composition with globular witness ───
 *
 * The first family of CATT_R_Yon is cell composition. Given
 * two cells f : s ->_A t and g : t ->_A u (matching boundaries),
 * their composition f ; g : s ->_A u is built as a coherence:
 *
 *   comp_2 : forall (x : star) (y : star) (z : star)
 *                   (f : x -> y) (g : y -> z). x -> z
 *
 * encoded as TmCoh ps_comp_2 (CellArr (TmVar "x", TmVar "z", CellStar))
 *
 * where ps_comp_2 is the standard composition pasting scheme
 * (Batanin) and the substitution provides the actual endpoints.
 *
 * The function below produces the witness when the boundaries match,
 * and returns None when they don't (incompatible cells cannot be
 * composed in a globular omega-category). *)

(* Helper: compute the source endpoint of a cell. *)
let cell_source (c : cell) : term option =
  match c with
  | CellStar -> None  (* 0-cells have no source *)
  | CellArr (s, _, _) -> Some s

(* Helper: compute the target endpoint of a cell. *)
let cell_target (c : cell) : term option =
  match c with
  | CellStar -> None
  | CellArr (_, t, _) -> Some t

(* Helper: extract the base cell (one dimension below). *)
let cell_dim_below (c : cell) : cell option =
  match c with
  | CellStar -> None
  | CellArr (_, _, base) -> Some base

(* Standard 1-cell composition pasting scheme:
 *   [x : *, y : *, f : x -> y, z : *, g : y -> z]
 * This is the canonical ps-ctx for composition of 1-cells.
 *
 * Naming: the variables are fixed strings; the user-side substitution
 * will rename them via subst when applying. *)
let ps_comp_2 : ps_ctx = [
  ("x", CellStar);
  ("y", CellStar);
  ("f", CellArr (TmVar "x", TmVar "y", CellStar));
  ("z", CellStar);
  ("g", CellArr (TmVar "y", TmVar "z", CellStar));
]

(* Compose two 1-cells. Returns Some witness when boundaries match,
 * None when they don't. The witness is a TmCoh applying the standard
 * comp_2 coherence to the actual endpoint values. *)
let cell_compose_1 (f_src : term) (f_tgt : term)
                   (g_src : term) (g_tgt : term)
                   : (term * cell) option =
  (* Globular composability: f's target must equal g's source. *)
  if not (alpha_equiv_term f_tgt g_src []) then None
  else
    let result_cell = CellArr (f_src, g_tgt, CellStar) in
    let result_term =
      TmCoh (ps_comp_2,
             result_cell,
             [("x", f_src);
              ("y", f_tgt);  (* = g_src by composability check *)
              ("f", TmVar "__f");  (* placeholders for the actual cells *)
              ("z", g_tgt);
              ("g", TmVar "__g")])
    in
    Some (result_term, result_cell)

(* Compose two cells of arbitrary matching dimension. Returns Some
 * when the cells are globularly composable (target of f equals source
 * of g at every dimension above the composition axis), None otherwise.
 *
 * For now we implement the 1-dimensional case (composition along
 * 0-cells = objects). Higher-dimensional composition along k-cells
 * with k > 0 (vertical, horizontal composition for 2-cells, etc.) is
 * left for the higher families. *)
let cell_compose (f_cell : cell) (g_cell : cell) : (term * cell) option =
  match f_cell, g_cell with
  | CellArr (fs, ft, fbase), CellArr (gs, gt, gbase) ->
      (* Both 1-cells (base is CellStar) or both n-cells with same base. *)
      if alpha_equiv_cell fbase gbase [] then
        cell_compose_1 fs ft gs gt
      else None
  | _ -> None

(* Test entry: compose simple 1-cells x -> y and y -> z, producing x -> z.
 * Returns true if composition produces a well-formed witness with
 * source x and target z. *)
let test_cell_composition () =
  let x = TmVar "x" and y = TmVar "y" and z = TmVar "z" in
  let f_cell = CellArr (x, y, CellStar) in
  let g_cell = CellArr (y, z, CellStar) in
  match cell_compose f_cell g_cell with
  | Some (_witness, CellArr (src, tgt, CellStar)) ->
      alpha_equiv_term src x [] && alpha_equiv_term tgt z []
  | _ -> false

(* Test the negative case: incompatible cells should not compose. *)
let test_cell_composition_incompat () =
  let x = TmVar "x" and y = TmVar "y" and z = TmVar "z" and w = TmVar "w" in
  let f_cell = CellArr (x, y, CellStar) in
  let g_cell = CellArr (z, w, CellStar) in  (* z != y *)
  match cell_compose f_cell g_cell with
  | None -> true
  | _ -> false

(* ─── Family 2 (constructive): identity coherences ────────────────────
 *
 * In an omega-category, for every cell f : x -> y there exist:
 *
 *   left_unit  : id_x ; f -> f     (left unitor: composing with the
 *                                    identity on the source is the
 *                                    identity transformation)
 *   right_unit : f ; id_y -> f    (right unitor: composing with the
 *                                    identity on the target is also
 *                                    the identity transformation)
 *   middle_four (associator):
 *     ((h ; g) ; f) -> (h ; (g ; f))
 *
 * These are 2-cells in CATT_R_Yon (one dimension above the cells
 * they witness equality between). The "middle four interchange" name
 * refers to the four 1-cells involved in the rebracketing.
 *
 * Below we produce these witnesses as TmCoh terms with appropriate
 * pasting schemes. *)

(* Pasting scheme for the left unitor witness:
 *   [x : star, y : star, f : x -> y]
 * The 2-cell witnessed is (id_x ; f) -> f. *)
let ps_left_unit : ps_ctx = [
  ("x", CellStar);
  ("y", CellStar);
  ("f", CellArr (TmVar "x", TmVar "y", CellStar));
]

(* Pasting scheme for the right unitor witness — same shape. *)
let ps_right_unit : ps_ctx = ps_left_unit

(* Pasting scheme for the associator:
 *   [w : star, x : star, y : star, z : star,
 *    h : w -> x, g : x -> y, f : y -> z]
 *)
let ps_associator : ps_ctx = [
  ("w", CellStar);
  ("x", CellStar);
  ("y", CellStar);
  ("z", CellStar);
  ("h", CellArr (TmVar "w", TmVar "x", CellStar));
  ("g", CellArr (TmVar "x", TmVar "y", CellStar));
  ("f", CellArr (TmVar "y", TmVar "z", CellStar));
]

(* Construct the left unitor witness for a 1-cell f : x -> y.
 * Returns the 2-cell (id_x ; f) -> f as a TmCoh. *)
let left_unitor (f_src : term) (f_tgt : term) : term =
  let base_cell = CellArr (f_src, f_tgt, CellStar) in
  (* The 2-cell is from (id_x ; f) to f, both at type base_cell. *)
  let id_x_compose_f =
    TmCoh (ps_comp_2, base_cell,
           [("x", f_src); ("y", f_src); ("f", TmId (f_src, CellStar));
            ("z", f_tgt); ("g", TmVar "__f")])
  in
  let f_term = TmVar "__f" in
  let witness_cell = CellArr (id_x_compose_f, f_term, base_cell) in
  TmCoh (ps_left_unit, witness_cell,
         [("x", f_src); ("y", f_tgt); ("f", f_term)])

(* Construct the right unitor witness for a 1-cell f : x -> y. *)
let right_unitor (f_src : term) (f_tgt : term) : term =
  let base_cell = CellArr (f_src, f_tgt, CellStar) in
  let f_compose_id_y =
    TmCoh (ps_comp_2, base_cell,
           [("x", f_src); ("y", f_tgt); ("f", TmVar "__f");
            ("z", f_tgt); ("g", TmId (f_tgt, CellStar))])
  in
  let f_term = TmVar "__f" in
  let witness_cell = CellArr (f_compose_id_y, f_term, base_cell) in
  TmCoh (ps_right_unit, witness_cell,
         [("x", f_src); ("y", f_tgt); ("f", f_term)])

(* Construct the associator witness for three composable 1-cells.
 * Witnesses ((h ; g) ; f) -> (h ; (g ; f)). *)
let associator (w : term) (x : term) (y : term) (z : term) : term =
  let base_cell = CellArr (w, z, CellStar) in
  let h_then_g = TmVar "__hg" in
  let hg_then_f = TmVar "__hgf_left" in
  let g_then_f = TmVar "__gf" in
  let h_then_gf = TmVar "__hgf_right" in
  let witness_cell = CellArr (hg_then_f, h_then_gf, base_cell) in
  TmCoh (ps_associator, witness_cell,
         [("w", w); ("x", x); ("y", y); ("z", z);
          ("h", h_then_g);
