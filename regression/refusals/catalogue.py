#!/usr/bin/env python3
"""The catalogue of refusals: every form Yon refuses, with its code, its message and its proof.

Yon is true only where every program that would break it does not compile. Each refusal ("no") of
the language is an entry here, and the entry is the rule: the diagnostic code (registered in
frontend/error_codes.ml, the one source of the codes), the message the compiler gives, why, how
the right form is written, the page of the book, and the refusal proofs: programs written wrong on
purpose. A proof is a folder of regression/canonical_forms/ (it is run by
regression/test_canonical_forms.py), or, while the compiler does not refuse the form yet, a draft
generated in regression/refusals/drafts/ from the entry. An entry whose proof cannot be written yet
says why (`proof_pending`). The state of an entry is read off the suite: a code in NO_PRODUCER of
regression/test_error_codes.py is registered and produced by no step yet.

This file is the source of the entries; regression/refusals/CATALOGUE.md and the drafts are
derived from it:

  python3 regression/refusals/catalogue.py           # rewrite CATALOGUE.md and the drafts
  python3 regression/refusals/catalogue.py --check   # exit 1 if they are stale, or if an entry and
                                                     # the refusal proofs do not match

The check goes both ways: every entry has a proof (a folder whose .expect is reject_clean with the
code of the entry, or with the code the proof gives until its step aligns it, `proof_code`), a draft
or a pending reason; and every reject_clean folder of regression/canonical_forms/ belongs to an
entry.
"""
