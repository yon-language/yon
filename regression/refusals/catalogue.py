class Stop(RuntimeError):
    pass


def error_codes() -> dict:
    """id -> (variant, title), read from frontend/error_codes.ml."""
    src = ERROR_CODES.read_text()

    def table(fn):
        m = re.search(r"\nlet " + fn + r" : code -> string = function\n(.*?)\n\n", src, re.S)
        if not m:
            raise Stop(f"frontend/error_codes.ml: no `let {fn} : code -> string = function`")
        return dict(re.findall(r'\|\s*([A-Z][A-Za-z_]*)\s*->\s*"((?:[^"\\]|\\.)*)"', m.group(1)))
    ids, titles = table("id"), table("title")
    return {i: (v, titles.get(v, "")) for v, i in ids.items()}


def no_producer() -> set:
    """The codes NO_PRODUCER of regression/test_error_codes.py lists: registered, produced by no step yet."""
    tree = ast.parse(TEST_CODES.read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "NO_PRODUCER" for t in node.targets):
            return set(ast.literal_eval(node.value))
    raise Stop("regression/test_error_codes.py: no NO_PRODUCER")


def number(i: int) -> str:
    return f"NO-{i:03d}"


def proof_text(e):
    """The text the caret of the entry points into: its draft, or its first proof folder."""
    if e.get("at") is None:
        return None
    f = e.get("at_file", "Entry.yon")
    if "draft" in e:
        return e["draft"].get(f)
    for p in e["proofs"]:
        path = CANONICAL / p / f
        if path.exists():
            return path.read_text()
    return None


def block(e):
    text = proof_text(e)
    lines = [f"error[{e['code']}]: {e['msg']}"]
    if text is not None:
        i = text.find(e["at"])
        if i < 0:
            raise Stop(f"{e['id']}: the caret `{e['at']}` is not in {e.get('at_file', 'Entry.yon')}")
        ln = text.count("\n", 0, i) + 1
        col = i - (text.rfind("\n", 0, i) + 1) + 1
        src = text.split("\n")[ln - 1]
        n = e.get("caret_len") or len(e["at"].split("\n")[0])
        w = len(str(ln))
        lines = [lines[0], " " * (w + 1) + f"--> {e.get('at_file', 'Entry.yon')}:{ln}:{col}", " " * (w + 2) + "|",
                 " " + str(ln).rjust(w) + " | " + src, " " * (w + 2) + "| " + " " * (col - 1) + "^" * n]
        pad = " " * (w + 2)
    else:
        pad = "   "
    lines.append(pad + f"= why: {e['why']}")
    if e.get("write"):
        lines.append(pad + f"= write: {e['write']}")
    return "\n".join(lines)


def drafts() -> dict:
    """path (relative to the drafts folder) -> text, for every entry with a draft."""
    out = {}
    for e in ENTRIES:
        if "draft" not in e:
            continue
        base = f"{e['construct']}/{e['dev']}"
        for rel, text in e["draft"].items():
            out[f"{base}/{rel}"] = text
        out[f"{base}.expect"] = "\n".join(["status: reject_clean", "exit: 1", f"code: {e['code']}",
                                           f"match: {e['msg']}"]) + "\n"
    return out


def check_proofs(codes) -> list:
    """What does not match between the entries and the refusal proofs, both ways."""
    problems, owned = [], {}
    seen = set()
    for i, e in enumerate(ENTRIES, 1):
        no = f"{number(i)} `{e['id']}`"
        key = (e["construct"], e["dev"])
        if key in seen:
            problems.append(f"{no}: a second entry for {e['construct']}/{e['dev']}")
        seen.add(key)
        if e["code"] not in codes:
            problems.append(f"{no}: the code {e['code']} is not registered in frontend/error_codes.ml")
        if not (e["proofs"] or "draft" in e or e.get("proof_pending")):
            problems.append(f"{no}: no proof, no draft and no pending reason")
        for p in e["proofs"]:
            owned[p] = no
            exp = CANONICAL / (p + ".expect")
            if not (CANONICAL / p).is_dir() or not exp.exists():
                problems.append(f"{no}: the proof {p} is not a folder of regression/canonical_forms")
                continue
            fields = dict(re.findall(r"^(\w+):\s*(.*)$", exp.read_text(), re.M))
            want = e.get("proof_code", {}).get(p, e["code"])
            if fields.get("status") != "reject_clean":
                problems.append(f"{no}: the proof {p} is not reject_clean")
            elif fields.get("code") != want:
                problems.append(f"{no}: the proof {p} gives {fields.get('code')}, the entry says {want}")
    for exp in sorted(CANONICAL.glob("*/*.expect")):
        fields = dict(re.findall(r"^(\w+):\s*(.*)$", exp.read_text(), re.M))
        p = f"{exp.parent.name}/{exp.stem}"
        if fields.get("status") == "reject_clean" and p not in owned:
            problems.append(f"the refusal proof {p} belongs to no entry")
    return problems


def render(codes, unproduced) -> str:
    L = ["# The catalogue of refusals", "",
         "Every form Yon refuses, with its code, its message and its proof. GENERATED from",
         "`regression/refusals/catalogue.py` (`" + COMMAND + "`); do not edit.", "",
         "Each entry: the code and the band that reads it (grammar: the lexer or the parser; checker: the",
         "type; project: the layout of the files; manifest: `yon.toml`), the message, why, how the right",
         "form is written, the page of the book, and its refusal proofs: folders of",
         "`regression/canonical_forms/`, or a draft in `regression/refusals/drafts/` while the compiler does",
         "not refuse the form yet. The state: a code that no step produces yet is in `NO_PRODUCER` of",
         "`regression/test_error_codes.py`.", ""]
    for s in SECTIONS:
        L += [f"## {SECTIONS[s]}", ""]
        for i, e in enumerate(ENTRIES, 1):
            if e["section"] != s:
                continue
            L += [f"### {number(i)} `{e['id']}` · {e['code']} · {e['band']}", ""]
            L.append(f"- book: {e['book']}")
            if e["proofs"]:
                pr = []
                for p in e["proofs"]:
                    c = e.get("proof_code", {}).get(p)
                    pr.append(f"`regression/canonical_forms/{p}`" + (f" (gives {c} until its step aligns it)" if c else ""))
                L.append("- proof: " + ", ".join(pr))
            if "draft" in e:
                L.append(f"- draft: `regression/refusals/drafts/{e['construct']}/{e['dev']}`")
            if e.get("proof_pending"):
                L.append(f"- proof to write: {e['proof_pending']}")
            if e["code"] in unproduced:
                L.append("- state: the code is registered and no step produces it yet")
            L += ["", "```", block(e), "```", ""]
    used = {}
    for e in ENTRIES:
        used[e["code"]] = used.get(e["code"], 0) + 1
    L += ["## The codes of the catalogue", "", "Read from `frontend/error_codes.ml`.", "",
          "| code | variant | title | entries |", "|---|---|---|---|"]
    for c in sorted(used):
        v, t = codes[c]
        L.append(f"| {c} | `{v}` | {t} | {used[c]} |")
    L.append("")
    return "\n".join(L)


def main() -> int:
    try:
        codes = error_codes()
        unproduced = no_producer()
        problems = check_proofs(codes)
        text = render(codes, unproduced)
        want = drafts()
    except Stop as e:
        print("catalogue stopped: " + str(e), file=sys.stderr)
        return 2
    have = {p.relative_to(DRAFTS).as_posix(): p for p in DRAFTS.rglob("*") if p.is_file()} if DRAFTS.exists() else {}
    stale = []
    if not CATALOGUE.exists() or CATALOGUE.read_text() != text:
        stale.append("regression/refusals/CATALOGUE.md")
    if set(have) != set(want) or any(have[p].read_text() != t for p, t in want.items() if p in have):
        stale.append("regression/refusals/drafts/")
    if "--check" in sys.argv[1:]:
        for p in problems:
            print("catalogue: " + p, file=sys.stderr)
        if stale:
            print("stale: " + ", ".join(stale) + f". Run: {COMMAND}", file=sys.stderr)
        if problems or stale:
            return 1
        print(f"the catalogue ({len(ENTRIES)} entries) and its proofs match")
        return 0
    if problems:
        for p in problems:
            print("catalogue: " + p, file=sys.stderr)
        return 1
    CATALOGUE.write_text(text)
    for p in set(have) - set(want):
        have[p].unlink()
    for p, t in want.items():
        path = DRAFTS / p
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != t:
            path.write_text(t)
    for d in sorted((x for x in DRAFTS.rglob("*") if x.is_dir()), key=lambda x: -len(x.parts)):
        if not any(d.iterdir()):
            d.rmdir()
    print(f"wrote regression/refusals/CATALOGUE.md and {len(want)} files of drafts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
